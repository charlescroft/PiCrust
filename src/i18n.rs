use serde::{Deserialize, Serialize};

#[derive(Debug, Clone, Copy, PartialEq, Eq, Default, Serialize, Deserialize)]
pub enum AppLocale {
    #[default]
    En,
    ZhCn,
}

impl AppLocale {
    pub fn all() -> &'static [Self] {
        &[Self::En, Self::ZhCn]
    }

    pub fn code(&self) -> &'static str {
        match self {
            Self::En => "en",
            Self::ZhCn => "zh-CN",
        }
    }

    pub fn from_code(code: &str) -> Self {
        match code.trim() {
            "zh" | "zh-CN" | "zh_CN" => Self::ZhCn,
            _ => Self::En,
        }
    }

    pub fn label(&self) -> &'static str {
        match self {
            Self::En => "English",
            Self::ZhCn => "简体中文",
        }
    }
}

pub fn tr(locale: AppLocale, key: &'static str) -> &'static str {
    match locale {
        AppLocale::En => en_text(key),
        AppLocale::ZhCn => zh_text(key),
    }
}

pub fn format_commas<T: std::fmt::Display>(val: T) -> String {
    let s = val.to_string();
    let is_negative = s.starts_with('-');
    let abs_s = if is_negative { &s[1..] } else { &s[..] };
    let (int_part, dec_part) = match abs_s.split_once('.') {
        Some((int, dec)) => (int, Some(dec)),
        None => (abs_s, None),
    };
    let chars: Vec<char> = int_part.chars().collect();
    let len = chars.len();
    let mut out = String::with_capacity(s.len() + 8);
    if is_negative {
        out.push('-');
    }
    for (i, c) in chars.into_iter().enumerate() {
        if i > 0 && (len - i) % 3 == 0 {
            out.push(',');
        }
        out.push(c);
    }
    if let Some(dec) = dec_part {
        out.push('.');
        out.push_str(dec);
    }
    out
}

pub fn format_tokens_km(n: u64) -> String {
    if n >= 1_000_000 {
        let m = n as f64 / 1_000_000.0;
        if (m - m.round()).abs() < 0.05 {
            format!("{}M", m.round() as u64)
        } else {
            format!("{m:.1}M")
        }
    } else if n >= 1_000 {
        let k = n as f64 / 1_000.0;
        if (k - k.round()).abs() < 0.05 {
            format!("{}K", k.round() as u64)
        } else {
            format!("{k:.1}K")
        }
    } else {
        n.to_string()
    }
}

