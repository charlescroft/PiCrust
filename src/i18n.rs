#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn translates_en_and_zh_cn() {
        assert_eq!(tr(AppLocale::En, "settings.title"), "Settings");
        assert_eq!(tr(AppLocale::ZhCn, "settings.title"), "设置");
        assert_eq!(AppLocale::from_code("zh-CN"), AppLocale::ZhCn);
        assert_eq!(AppLocale::from_code("en"), AppLocale::En);
    }

    #[test]
    fn formats_numbers_with_commas() {
        assert_eq!(format_commas(0), "0");
        assert_eq!(format_commas(999), "999");
        assert_eq!(format_commas(1000), "1,000");
        assert_eq!(format_commas(1234567), "1,234,567");
        assert_eq!(format_commas(-12345), "-12,345");
        assert_eq!(format_commas("12345.678"), "12,345.678");
    }

    #[test]
    fn formats_tokens_in_k_and_m() {
        assert_eq!(format_tokens_km(320), "320");
        assert_eq!(format_tokens_km(1_400), "1.4K");
        assert_eq!(format_tokens_km(200_000), "200K");
        assert_eq!(format_tokens_km(1_250_000), "1.2M");
    }
}
